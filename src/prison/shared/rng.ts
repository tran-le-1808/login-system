/** RNG có hạt giống (mulberry32), trạng thái lưu trong WorldState để kết quả tái lập được. */
export function nextRandom(state: { rngState: number }): number {
  let t = (state.rngState = (state.rngState + 0x6d2b79f5) | 0);
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

export function pick<T>(state: { rngState: number }, list: readonly T[]): T {
  return list[Math.floor(nextRandom(state) * list.length) % list.length];
}
